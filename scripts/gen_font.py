#!/usr/bin/env python3
"""Convert TTF fonts into compact 1-bit bitmap fonts for the Sticky e-paper.

Usage: python3 scripts/gen_font.py OUT.h NAME:TTF:PX [NAME:TTF:PX ...]

Each glyph is rendered with Pillow (anti-aliased), thresholded to 1 bit and
cropped to its ink box. Bits are packed MSB-first, row-major, continuously
across rows (Adafruit-GFX style). Coverage: printable ASCII 0x20..0x7E.
Output types (StickyFont / StickyGlyph) are declared in gfx.h.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E
THRESHOLD = 110  # < 128 keeps thin strokes of small sizes alive


def render(name, ttf, px):
    font = ImageFont.truetype(ttf, px)
    ascent, descent = font.getmetrics()
    bits, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to baseline
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            px_ = img.load()
            for y in range(h):
                for x in range(w):
                    bits.append(1 if px_[x, y] >= THRESHOLD else 0)
        else:
            w = h = 0
        glyphs.append((off, w, h, adv, l, t))
    data = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for j, bit in enumerate(bits[i:i + 8]):
            byte |= bit << (7 - j)
        data.append(byte)
    out = [f"// {name}: {ttf.split('/')[-1]} @ {px}px, ascent {ascent}, descent {descent}"]
    out.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const StickyGlyph {name}_glyphs[] = {{")
    for code, (off, w, h, adv, xo, yo) in zip(range(FIRST, LAST + 1), glyphs):
        c = chr(code)
        label = c if c not in "\\'" else "\\" + c
        out.append(f"  {{{off},{w},{h},{adv},{xo},{yo}}}, // '{label}'")
    out.append("};")
    out.append(f"static const StickyFont {name} = {{ {name}_bits, {name}_glyphs, "
               f"{FIRST}, {LAST}, {ascent}, {descent} }};")
    return "\n".join(out), len(data)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    parts = ["// Generated by scripts/gen_font.py - do not edit.",
             "// Geist (c) Vercel, SIL Open Font License 1.1: assets/fonts/Geist-OFL.txt",
             "#pragma once", '#include "gfx_types.h"', ""]
    total = 0
    for spec in sys.argv[2:]:
        name, ttf, px = spec.split(":")
        text, n = render(name, ttf, int(px))
        parts += [text, ""]
        total += n
        print(f"{name}: {n} bytes of bitmap")
    open(sys.argv[1], "w").write("\n".join(parts))
    print(f"wrote {sys.argv[1]} ({total} bitmap bytes)")


if __name__ == "__main__":
    main()
