static const uint8_t* glyphLookup(char ch) {
  if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 'a' + 'A');
  for (const auto& g : FONT) if (g.ch == ch) return g.rows;
  for (const auto& g : FONT) if (g.ch == '?') return g.rows;
  return FONT[0].rows;
}

static void drawGlyph(int x, int y, const uint8_t rows[7], int scale, bool black) {
  for (int yy=0; yy<7; ++yy)
    for (int xx=0; xx<5; ++xx)
      if (rows[yy] & (16 >> xx))
        for (int sy=0; sy<scale; ++sy)
          for (int sx=0; sx<scale; ++sx)
            stickyDrawPixel(x + xx*scale + sx, y + yy*scale + sy, black);
}
static int textWidth(const char* s, int scale) {
  if (!s || !scale) return 0;
  int n = strlen(s); if (n > 200) n = 200;
  return (n*6 - 1) * scale;
}
static void drawText(int x, int y, const char* s, int scale = 1, bool black = true) {
  if (!s || !scale) return;
  for (; *s; ++s, x += 6*scale) drawGlyph(x, y, glyphLookup(*s), scale, black);
}
static void drawTextCentered(int cx, int y, const char* s, int scale = 1, bool black = true) {
  drawText(cx - textWidth(s, scale)/2, y, s, scale, black);
}
